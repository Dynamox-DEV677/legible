/**
 * Build Legible's bundled language data from the upstream datasets in .cache/.
 *
 *   node tools/fetch-data.mjs     (once: downloads the two datasets)
 *   node tools/build-data.mjs
 *
 * Writes:
 *   data/common-words.txt                 the everyday-word list, most common first
 *   src/core/data/common-words.js         the same list, pruned and front-coded
 *   src/core/data/syllable-exceptions.js  common words the syllable rules get wrong
 *   test/fixtures/cmu-syllables.txt       reference syllable counts used by `npm test`
 *
 * The outputs are committed, so nobody needs the datasets just to run or test Legible.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { agrees, loadCmuSyllables, loadFrequencyList } from './lib/datasets.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...parts) => join(root, ...parts);
const read = (...parts) => readFileSync(at(...parts), 'utf8');
const write = (path, text) => {
  mkdirSync(dirname(at(path)), { recursive: true });
  writeFileSync(at(path), text);
  console.log(`  wrote ${path} (${(Buffer.byteLength(text) / 1024).toFixed(1)} KB)`);
};

const LIST_SIZE = 5000;
/** How far down the frequency list the syllable exception table reaches. */
const EXCEPTION_DEPTH = 12000;

/** Halves of contractions that the subtitle corpus split apart: "don" + "'t". */
const FRAGMENTS = new Set(
  ('don didn doesn isn wasn aren weren couldn wouldn shouldn hasn haven hadn ain mustn needn ' +
    'shan ll ve re').split(' '),
);
/** Strong profanity and slurs are left out so the published list is safe to open in a classroom. */
const NOT_FOR_CLASSROOMS =
  /^(?:fuck|motherfuck|shit|bullshit|horseshit|cunt|bitch|asshole|nigg|fagg?ot|fags?$|whore|slut|puss(?:y|ies)$|cock(?:s|suckers?)?$|dick(?:s|heads?)?$|tit(?:s|ties)?$|twat|wank|jizz|cum$|blowjob|dildo)/;

if (process.argv.includes('--syllables')) await buildSyllables();
else await buildWords();

/* ------------------------------------------------------------------------------------ */

async function buildWords() {
  console.log('Everyday-word list');
  const { baseForms, decodeWordList, encodeWordList } = await import('../src/core/words.js');

  const ranked = loadFrequencyList(read('.cache', 'en_50k.txt'))
    .map((entry) => entry.word)
    .filter((word) => !FRAGMENTS.has(word) && !NOT_FOR_CLASSROOMS.test(word));
  const top = ranked.slice(0, LIST_SIZE);
  const listed = new Set(top);

  const screenWords = read('data', 'screen-words.txt')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'));
  const added = screenWords.filter((word) => !listed.has(word));
  for (const word of added) listed.add(word);

  write(
    'data/common-words.txt',
    [
      `# The ${LIST_SIZE} most frequent English word forms in film and television subtitles,`,
      '# most common first. Built by tools/build-data.mjs from FrequencyWords (OpenSubtitles',
      '# 2018). Licensed CC BY-SA 4.0. See data/README.md for attribution and changes.',
      ...top,
      '',
    ].join('\n'),
  );

  // Leave out every form the lookup can rebuild from a shorter word that is kept.
  // Shortest first, so a word is only ever dropped in favour of one already kept.
  const kept = new Set();
  for (const word of [...listed].sort((a, b) => a.length - b.length || (a < b ? -1 : 1))) {
    if (!baseForms(word).some((base) => kept.has(base))) kept.add(word);
  }
  const encoded = encodeWordList(kept);

  // Prove the round trip: decoding gives back exactly what was kept, and every word on
  // the published list is still recognised through the same lookup the app uses.
  const decoded = decodeWordList(encoded);
  if (decoded.size !== kept.size || [...kept].some((word) => !decoded.has(word))) {
    throw new Error('front-coding did not round-trip');
  }
  const lost = [...listed].filter((word) => !decoded.has(word) && !baseForms(word).some((base) => decoded.has(base)));
  if (lost.length) throw new Error(`pruning lost ${lost.length} words, e.g. ${lost.slice(0, 5).join(', ')}`);

  write(
    'src/core/data/common-words.js',
    [
      '// GENERATED by tools/build-data.mjs. Do not edit by hand.',
      '// Everyday English words, front-coded. Source, licence (CC BY-SA 4.0) and method: data/README.md.',
      `export const COMMON_WORDS = '${encoded}';`,
      `export const COMMON_WORDS_INFO = ${JSON.stringify({ listed: top.length, screenWords: added.length, stored: kept.size })};`,
      '',
    ].join('\n'),
  );
  console.log(
    `  ${top.length} listed + ${added.length} screen words = ${listed.size}; ` +
      `${kept.size} stored after pruning regular forms; ${encoded.length} characters`,
  );

  // The syllable step must see the new list, so it runs in a fresh process.
  execFileSync(process.execPath, [fileURLToPath(import.meta.url), '--syllables'], { stdio: 'inherit' });
}

async function buildSyllables() {
  console.log('Syllable exception table');
  // Start from an empty table so the measurement below is of the rules alone.
  write(
    'src/core/data/syllable-exceptions.js',
    "// GENERATED by tools/build-data.mjs. Do not edit by hand.\nexport const SYLLABLE_EXCEPTIONS = '';\n",
  );
  const { heuristicSyllables, lookupException, manualExceptions } = await import('../src/core/syllables.js');

  const cmu = loadCmuSyllables(read('.cache', 'cmudict.dict'));
  const ranked = loadFrequencyList(read('.cache', 'en_50k.txt')).map((entry) => entry.word);
  const candidates = ranked.slice(0, EXCEPTION_DEPTH).filter((word) => cmu.has(word));

  const rulesRight = candidates.filter((word) => agrees(word, heuristicSyllables(word), cmu.get(word))).length;

  // Singulars first, so that a plural can borrow its singular's entry instead of adding one.
  const manual = manualExceptions();
  const table = new Map(manual);
  const byCount = new Map();
  let generated = 0;
  for (const wanted of [(word) => !word.endsWith('s'), (word) => word.endsWith('s')]) {
    for (const word of candidates.filter(wanted)) {
      const truth = cmu.get(word);
      const got = lookupException(table, word) ?? heuristicSyllables(word);
      if (agrees(word, got, truth) || manual.has(word)) continue; // right already, or a deliberate choice
      const primary = [...truth][0];
      table.set(word, primary);
      if (!byCount.has(primary)) byCount.set(primary, []);
      byCount.get(primary).push(word);
      generated++;
    }
  }
  const encoded = [...byCount.keys()]
    .sort((a, b) => a - b)
    .map((count) => `${count}:${byCount.get(count).sort().join(' ')}`)
    .join('|');

  write(
    'src/core/data/syllable-exceptions.js',
    [
      '// GENERATED by tools/build-data.mjs. Do not edit by hand.',
      `// ${generated} of the ${EXCEPTION_DEPTH.toLocaleString('en')} most common words where spelling rules give the wrong syllable`,
      '// count, with the count from the CMU Pronouncing Dictionary (BSD licence, see',
      '// data/README.md). Format: "count:word word|count:word".',
      `export const SYLLABLE_EXCEPTIONS =\n  '${encoded}';`,
      '',
    ].join('\n'),
  );
  console.log(
    `  rules alone agree on ${rulesRight}/${candidates.length} ` +
      `(${((100 * rulesRight) / candidates.length).toFixed(2)}%) of the top ${EXCEPTION_DEPTH}; ${generated} generated exceptions`,
  );

  // Reference counts for the tests: every listed everyday word the dictionary knows.
  const listed = read('data', 'common-words.txt')
    .split(/\r?\n/)
    .filter((line) => line && !line.startsWith('#'));
  const fixture = listed.filter((word) => cmu.has(word)).map((word) => `${word} ${[...cmu.get(word)].join('/')}`);
  write(
    'test/fixtures/cmu-syllables.txt',
    [
      '# Syllable counts for Legible\'s everyday-word list, derived from the CMU Pronouncing',
      '# Dictionary (Copyright (C) 1993-2015 Carnegie Mellon University, BSD licence; see',
      '# data/README.md). Format: word count[/alternative count]. Built by tools/build-data.mjs.',
      ...fixture,
      '',
    ].join('\n'),
  );
}
