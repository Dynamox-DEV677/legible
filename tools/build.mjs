/**
 * Build the parts of Legible that cannot be served as plain source files.
 *
 *   node tools/build.mjs
 *
 * The app itself needs no build: index.html loads the modules in src/ directly. This
 * script makes three things and commits them, so the site still deploys as static files.
 *
 *   dist/legible.page.js   Legible as one self-contained script
 *   dist/bookmarklet.txt   the same script as a javascript: address, ready to bookmark
 *   sw.js                  the service worker, with the list of files to keep offline
 */

import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { build, transform } from 'esbuild';
import { toBookmarklet } from './lib/bookmarklet.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...parts) => join(root, ...parts);
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

/* ---- 1. One script ---- */
const css = (await transform(readFileSync(at('src/ui/reader.css'), 'utf8'), { loader: 'css', minify: true })).code.trim();
const bundle = await build({
  entryPoints: [at('src/bookmarklet/main.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['chrome100', 'firefox100', 'safari15.4'],
  legalComments: 'none',
  charset: 'utf8',
  write: false,
  plugins: [
    {
      // The stylesheet travels inside the script as a string, already minified.
      name: 'inline-css',
      setup(b) {
        b.onLoad({ filter: /reader\.css$/ }, () => ({ contents: css, loader: 'text' }));
      },
    },
  ],
});
const script = bundle.outputFiles[0].text.trim();
mkdirSync(at('dist'), { recursive: true });
writeFileSync(at('dist/legible.page.js'), script + '\n');

/* ---- 2. One bookmark ---- */
const bookmarklet = toBookmarklet(script);
writeFileSync(at('dist/bookmarklet.txt'), bookmarklet + '\n');

console.log('Bookmarklet');
console.log(`  script ${kb(Buffer.byteLength(script))} (${kb(gzipSync(script).length)} gzipped), of which styles ${kb(css.length)}`);
console.log(`  as a bookmark: ${bookmarklet.length.toLocaleString('en')} characters`);

/* ---- 3. Offline ---- */
function filesUnder(dir, keep) {
  const out = [];
  for (const name of readdirSync(at(dir))) {
    const path = `${dir}/${name}`;
    if (statSync(at(path)).isDirectory()) out.push(...filesUnder(path, keep));
    else if (keep(path)) out.push(path);
  }
  return out;
}
const files = [
  'index.html',
  'manifest.webmanifest',
  'README.md',
  'dist/bookmarklet.txt',
  'dist/legible.page.js',
  ...filesUnder('icons', () => true),
  // Everything the page imports. The bookmarklet entry is only ever used through dist/.
  ...filesUnder('src', (path) => /\.(?:js|css)$/.test(path) && !path.startsWith('src/bookmarklet/')),
].sort();

const hash = createHash('sha256');
for (const file of files) hash.update(file).update(readFileSync(at(file)));
const version = `legible-${hash.digest('hex').slice(0, 12)}`;

writeFileSync(
  at('sw.js'),
  `// GENERATED by tools/build.mjs. Do not edit by hand.
//
// Legible's service worker. On the first visit it saves every file the app needs, so
// from then on the app opens with no network at all. It only ever answers requests for
// this site's own files, and it never sends anything anywhere.

const VERSION = '${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(VERSION)
      .then((cache) => cache.addAll(FILES))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) => Promise.all(names.filter((name) => name !== VERSION).map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return;
  // Saved copy first, so a visit never waits on the network. A new build has a new
  // VERSION, which replaces the saved copy the next time the page is opened.
  event.respondWith(caches.match(event.request, { ignoreSearch: true }).then((saved) => saved || fetch(event.request)));
});
`,
);
const total = files.reduce((n, file) => n + statSync(at(file)).size, 0);
console.log('Offline');
console.log(`  ${files.length} files, ${kb(total)} in all, cache ${version}`);
console.log(`  ${relative(root, at('sw.js'))} written`);
